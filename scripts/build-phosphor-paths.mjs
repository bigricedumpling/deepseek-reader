/*
 * Generate a compact path map from @phosphor-icons/core.
 *
 * The Vue package ships ~1500 component wrappers; importing all of them puts a
 * very large chunk on the first-screen path. The app only needs two weights
 * (regular / fill), so store the SVG bodies once and render them with one small
 * component instead.
 */
import fs from 'node:fs'
import path from 'node:path'

const root = 'node_modules/@phosphor-icons/core/assets'
const regularDir = path.join(root, 'regular')
const fillDir = path.join(root, 'fill')
const out = path.resolve('src/utils/phosphor-paths.js')

function pascal(name) {
  return 'Ph' + name
    .split('-')
    .map(part => part ? part[0].toUpperCase() + part.slice(1) : '')
    .join('')
}

function body(file) {
  const raw = fs.readFileSync(file, 'utf8')
  const match = raw.match(/<svg[^>]*>([\s\S]*)<\/svg>\s*$/)
  return (match ? match[1] : raw).trim()
}

const files = fs.readdirSync(regularDir).filter(file => file.endsWith('.svg')).sort()
const entries = []
const missingFill = []
for (const file of files) {
  const base = file.slice(0, -4)
  const name = pascal(base)
  const fillFile = path.join(fillDir, base + '-fill.svg')
  const hasFill = fs.existsSync(fillFile)
  if (!hasFill) missingFill.push(base)
  entries.push(`  ${JSON.stringify(name)}: { regular: ${JSON.stringify(body(path.join(regularDir, file)))}${hasFill ? `, fill: ${JSON.stringify(body(fillFile))}` : ''} }`)
}

fs.writeFileSync(out, `/* Generated by scripts/build-phosphor-paths.mjs. */\nexport const phosphorPaths = {\n${entries.join(',\n')}\n}\n`)
console.log(`wrote ${entries.length} icons (${missingFill.length} without fill) to ${out}`)
