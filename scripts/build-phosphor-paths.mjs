/*
 * Generate compact path maps from @phosphor-icons/core.
 *
 * The Vue package ships ~1500 component wrappers; importing all of them puts a
 * very large chunk on the first-screen path. The app only needs two weights
 * (regular / fill), so store the SVG bodies once and render them with one small
 * component instead.
 *
 * Two outputs:
 * - phosphor-core.js: icons used by the default knowledge-base UI, imported eagerly.
 * - phosphor-paths.js: the full picker set, loaded only when it is needed.
 */
import fs from 'node:fs'
import path from 'node:path'
import { ICON_ALIASES } from '../src/utils/icon-aliases.js'

const root = 'node_modules/@phosphor-icons/core/assets'
const regularDir = path.join(root, 'regular')
const fillDir = path.join(root, 'fill')
const fullOut = path.resolve('src/utils/phosphor-paths.js')
const coreOut = path.resolve('src/utils/phosphor-core.js')

function pascal(name) {
  return 'Ph' + name
    .split('-')
    .map(part => part ? part[0].toUpperCase() + part.slice(1) : '')
    .join('')
}

function body(file) {
  const raw = fs.readFileSync(file, 'utf8')
  const match = raw.match(/<svg[^>]*>([\s\S]*)<\/svg>\s*$/)
  return (match ? match[1] : raw).trim()
}

/* Core keys are the hand-picked block at the top of icon-catalog.js. */
const catalog = fs.readFileSync(path.resolve('src/utils/icon-catalog.js'), 'utf8')
const coreBlock = catalog.slice(
  catalog.indexOf('const LIBRARY = ['),
  catalog.indexOf('/* 以上是首屏和知识库默认图标')
)
const coreNames = new Set(
  [...coreBlock.matchAll(/\['[^']+',\s*'[^']*',\s*'(Ph\w+)'\]/g)]
    .map(match => ICON_ALIASES[match[1]] || match[1])
)
coreNames.add('PhFileText')

const files = fs.readdirSync(regularDir).filter(file => file.endsWith('.svg')).sort()
const fullEntries = []
const coreEntries = []
const missingFill = []
for (const file of files) {
  const base = file.slice(0, -4)
  const name = pascal(base)
  const fillFile = path.join(fillDir, base + '-fill.svg')
  const hasFill = fs.existsSync(fillFile)
  if (!hasFill) missingFill.push(base)
  const entry = `  ${JSON.stringify(name)}: { regular: ${JSON.stringify(body(path.join(regularDir, file)))}${hasFill ? `, fill: ${JSON.stringify(body(fillFile))}` : ''} }`
  fullEntries.push(entry)
  if (coreNames.has(name)) coreEntries.push(entry)
}

fs.writeFileSync(fullOut, `/* Generated by scripts/build-phosphor-paths.mjs. */\nexport const phosphorPaths = {\n${fullEntries.join(',\n')}\n}\n`)
fs.writeFileSync(coreOut, `/* Generated by scripts/build-phosphor-paths.mjs. */\nexport const phosphorCore = {\n${coreEntries.join(',\n')}\n}\n`)
console.log(`wrote ${fullEntries.length} icons (${missingFill.length} without fill) to ${fullOut}`)
console.log(`wrote ${coreEntries.length} core icons to ${coreOut}`)
